"""端到端自测: 用合成 matrix 检验 slpi_spatial_analysis 全流程（读 mtx / 归一化 / Moran's I / 出图）"""
import gzip
import os
import shutil
import sys
import time

import numpy as np

sys.path.insert(0, r"f:\ai_paper\experiment2_fm_time\scripts")
import slpi_spatial_analysis as ana

SRC = ana.DATA_DIR
TMP = r"f:\ai_paper\experiment2_fm_time\data\visium_luad\selftest"
os.makedirs(TMP, exist_ok=True)

for f in ("GSM5702473_TD1_features.tsv.gz", "GSM5702473_TD1_barcodes.tsv.gz",
          "GSM5702473_TD1_tissue_positions_list.csv.gz"):
    dst = os.path.join(TMP, f)
    if not os.path.exists(dst):
        shutil.copyfile(os.path.join(SRC, f), dst)

# 读 barcodes / positions 以生成与真实矩阵同构的合成计数
barcodes = [r[0] for r in ana.read_tsv_gz(os.path.join(TMP, "GSM5702473_TD1_barcodes.tsv.gz"), 1)]
pos_rows = []
with gzip.open(os.path.join(TMP, "GSM5702473_TD1_tissue_positions_list.csv.gz"), "rt") as fh:
    for line in fh:
        p = line.rstrip("\n").split(",")
        if len(p) >= 6:
            pos_rows.append(p)
pos_bc = [p[0] for p in pos_rows]
rows_set = set(barcodes) & set(pos_bc)
bc2pos = {p[0]: (float(p[4]), float(p[5])) for p in pos_rows}

SLPI_ROW = 33493          # 1-based 行号（pipeline 中 0-based 33492 -> 1-based 33493）
N_GENES, N_SPOTS = 36601, len(barcodes)

rng = np.random.default_rng(7)
entries = []

# 1) SLPI 行: 沿坐标的平滑场 (高 Moran's I)，用于验证"高自相关 -> 显著"分支
for j, bc in enumerate(barcodes, start=1):
    if bc in rows_set:
        x, y = bc2pos[bc]
        base = 12 + 6 * np.sin(x / 2500.0) * np.cos(y / 3000.0)
        v = int(max(0, round(base + rng.normal(0, 0.8))))
    else:
        v = 1
    entries.append((SLPI_ROW, j, v))

# 2) 其它行的少量条目, 使每 spot 总计数合理 (~2000)
for j in range(1, N_SPOTS + 1):
    k = 120
    ridx = rng.choice(np.arange(1, N_GENES + 1), size=k, replace=False)
    for r in ridx:
        if r == SLPI_ROW:
            continue
        entries.append((int(r), j, int(rng.poisson(15) + 1)))

entries.sort(key=lambda t: (t[0], t[1]))
mtx_path = os.path.join(TMP, "GSM5702473_TD1_matrix.mtx.gz")
with gzip.open(mtx_path, "wt") as fh:
    fh.write("%%MatrixMarket matrix coordinate integer general\n")
    fh.write("%Generated by synthetic self-test\n")
    fh.write(f"{N_GENES} {N_SPOTS} {len(entries)}\n")
    for r, c, v in entries:
        fh.write(f"{r} {c} {v}\n")
print("合成 matrix 大小 = %.1f MB, nnz = %d" % (os.path.getsize(mtx_path) / 1e6, len(entries)))

ana.DATA_DIR = TMP
ana.OUT_DIR = TMP
ana.N_PERM = 200
t0 = time.time()
ana.main()
print("端到端自测耗时 = %.1f s" % (time.time() - t0))
